@unittest.skipUnless(CONEXAO, 'Defina SAFECLICK_TEST_DATABASE_URL para o PostgreSQL local dedicado.')
class ParticipacaoPostgresTeste(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        info = conninfo_to_dict(CONEXAO)
        if info.get('host') not in {'127.0.0.1', 'localhost'} or info.get('dbname') != 'safeclick_participacao_test':
            raise RuntimeError('Os testes de integração exigem o banco local safeclick_participacao_test.')
        cls.c = psycopg.connect(CONEXAO, row_factory=dict_row, autocommit=True)
        # O banco dedicado deve estar vazio. Não apaga tabelas de outras execuções.
        if cls.c.execute("SELECT to_regclass('public.usuarios') AS tabela").fetchone()['tabela'] is not None:
            cls.c.close()
            raise RuntimeError('Use um banco de integração vazio.')
        cls.c.execute(ESQUEMA)
        cls.c.execute((RAIZ / 'sql/criar_avaliacoes.sql').read_text(encoding='utf-8'))
        cls.c.execute((RAIZ / 'sql/adicionar_avaliacoes_publicas_ranking.sql').read_text(encoding='utf-8'))
        cls.c.execute((RAIZ / 'sql/remover_ranking.sql').read_text(encoding='utf-8'))

    @classmethod
    def tearDownClass(cls):
        cls.c.execute('DROP VIEW public.resultados_validos_atividades; DROP TABLE logs_auditoria,avaliacoes_conteudo,avaliacoes_quiz,conclusoes_conteudo,respostas_tentativa_quiz,tentativas_quiz,alternativas,questoes,quizzes,catalogo_quizzes,conteudos,tentativas_simulacao,versoes_simulacao,simulacoes,desafios_senha,usuarios CASCADE; DROP FUNCTION public.limpar_participacao_conta()')
        cls.c.close()

