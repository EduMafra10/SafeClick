        self.c.execute("INSERT INTO catalogo_quizzes(id,estado,versao_publicada_id) VALUES(21,'publicada',201)")
        self.c.execute("INSERT INTO quizzes(id,catalogo_id,titulo) VALUES(201,21,'Quiz de senhas')")
